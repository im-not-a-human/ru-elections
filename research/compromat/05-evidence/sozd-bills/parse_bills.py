def parse(fn):
    bid = fn.replace(".html","")
    html = open(fn).read()
    m1 = re.search(r"<title>([^<]+)</title>", html)
    title_html = m1.group(1) if m1 else ""
    msub = re.search(r"Субъект[^<]*законодательной инициативы.{0,15000}", html, re.DOTALL)
    sub_block = msub.group(0) if msub else ""
    names = re.findall(r"[А-ЯЁ]\.[А-ЯЁ]\.[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?", sub_block)
    actor = "unknown"
    if "Президент Российской Федерации" in sub_block:
        actor = "Президент РФ"
    elif "Правительство Российской Федерации" in sub_block:
        actor = "Правительство РФ"
    elif "Депутат" in sub_block or "Член Совета" in sub_block:
        actor = "Депутаты ГД / Сенаторы"
    event_dates = re.findall(r'data-eventdate="(20\d\d-\d\d-\d\d)', html)
    mfz = re.search(r"№\s*(\d{1,3})-ФЗ\s+от\s+(\d{2}\.\d{2}\.20\d{2})", html)
    fz_num = mfz.group(1) if mfz else ""
    fz_date = mfz.group(2) if mfz else ""
    # Try multiple title extractions
    full_title = ""
    for pat in [
        r'class="name_text"[^>]*>([^<]{10,500})',
        r'class="naimenovanie[^"]*"[^>]*>([^<]{10,500})',
        r'<h2[^>]*>([^<]{10,500})</h2>',
        r'<h1[^>]*>\s*([^<]{10,500})\s*</h1>'
    ]:
        m = re.search(pat, html)
        if m:
            full_title = m.group(1).strip()
            break
    # If not found, search for legal title pattern
    if not full_title or "наименование" in full_title.lower():
        # Look for "О внесении изменений" patterns near top
        ms = re.findall(r"О\s+(?:внесении|введении|приостановлении|признании|ратификации|закреплении|связи с|развитии)[^<]{20,400}", html)
        if ms:
            full_title = ms[0].strip()
    found_key = sorted(set(KEY_NAMES.get(n, None) for n in names) - {None})
    return {
        "bill_number": bid,
        "title_html": title_html,
        "actor_type": actor,
        "fz_number": fz_num,
        "fz_date": fz_date,
        "full_title": full_title[:500],
        "authors_total_count": len(set(names)),
        "authors_initials_unique": sorted(set(names)),
        "key_authors_with_party": found_key,
        "event_dates": sorted(set(event_dates))
    }


if __name__ == "__main__":
    out = {}
    for f in sorted(glob.glob("[0-9]*.html")):
        out[f.replace(".html","")] = parse(f)
    print(json.dumps(out, ensure_ascii=False, indent=1))
